let activeChapterKey = 'ch6_1';
let userSelections = {};

function switchChapter(key) {
    activeChapterKey = key;
    document.querySelectorAll('nav button').forEach(btn => btn.classList.remove('active'));
    document.getElementById('nav-' + key).classList.add('active');
    renderChapter(key);
}

function renderChapter(key) {
    const chap = syllabusData[key];
    userSelections[key] = new Array(chap.quiz.length).fill(null);

    let notesHTML = chap.notes.map(n => `<li>${n}</li>`).join('');

    let quizHTML = chap.quiz.map((q, qIdx) => {
        let optionsHTML = q.options.map((opt, optIdx) => `
            <label class="option-label">
                <input type="radio" name="q_${key}_${qIdx}" value="${optIdx}" onclick="recordAnswer('${key}', ${qIdx}, ${optIdx})">
                ${opt}
            </label>
        `).join('');

        return `
            <div class="question-card">
                <span class="badge">Question ${qIdx + 1} of 5</span>
                <h4>${q.question}</h4>
                <div>${optionsHTML}</div>
            </div>
        `;
    }).join('');

    document.getElementById('chapter-view').innerHTML = `
        <div style="margin-bottom: 2rem;">
            <h2>${chap.title}</h2>
            <p class="subtitle">Review the official lecture notes below, then test your understanding with the 5-question self-evaluation quiz.</p>
        </div>

        <!-- Notes Section -->
        <div class="card">
            <h3>📖 Official Lecture Summary Notes</h3>
            <ul>${notesHTML}</ul>
        </div>

        <!-- Quiz Section -->
        <div>
            <h3 style="color: #312e81; font-size: 1.125rem; font-weight: bold; margin-bottom: 1rem;">✍️ Topic Self-Evaluation Quiz (5 Questions)</h3>
            <div>${quizHTML}</div>
            <button onclick="gradeQuiz('${key}')" class="btn-submit">Submit Quiz & View Score</button>
            <div id="result-box-${key}"></div>
        </div>
    `;
}

function recordAnswer(chapKey, qIdx, optIdx) {
    if (!userSelections[chapKey]) userSelections[chapKey] = [];
    userSelections[chapKey][qIdx] = optIdx;
}

function gradeQuiz(key) {
    const chap = syllabusData[key];
    const selections = userSelections[key];

    if (selections.includes(null)) {
        alert("Please answer all 5 questions before submitting your quiz!");
        return;
    }

    let score = 0;
    chap.quiz.forEach((q, idx) => {
        if (selections[idx] === q.answer) score++;
    });

    const pct = (score / 5) * 100;
    let resultClass = pct >= 80 ? 'result-success' : 'result-warning';

    document.getElementById(`result-box-${key}`).innerHTML = `
        <div class="result-box ${resultClass}">
            <h4>Quiz Completed! 🎉</h4>
            <p>Your Score: <strong>${score} / 5</strong> (${pct}%)</p>
            <p class="small">${pct >= 80 ? 'Outstanding! You have a firm grasp of these chapter concepts.' : 'Review the summary notes above and try again to master this topic.'}</p>
            <button onclick="renderChapter('${key}')" class="btn-retake">Retake Quiz</button>
        </div>
    `;
}

